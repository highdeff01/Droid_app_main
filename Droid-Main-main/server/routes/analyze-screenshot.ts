import { RequestHandler } from "express";
import { spawn } from "child_process";
import path from "path";
import { fileURLToPath } from "url";
import { gameStateManager } from "../state-manager";
import { autoTaskGenerator } from "../auto-task-generator";
import { multiAgentExecutor } from "../multi-agent-executor";
import { buildVisionMessage, sendQwenChatRequest } from "../ai-endpoint";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

interface AnalysisRequest {
  imageData: string;
  endpoint: string;
}

interface AnalysisResponse {
  success: boolean;
  simulated?: boolean;
  source?: "model" | "heuristic";
  detection?: string;
  suggestion?: string;
  confidence?: number | null;
  entities?: any[];
  autoGeneratedTasks?: any[];
  gameState?: any;
  executionResults?: any[];
  error?: string;
}

export const handleAnalyzeScreenshot: RequestHandler = async (req, res) => {
  try {
    const { imageData, endpoint } = req.body as AnalysisRequest;

    if (!imageData) {
      return res.json({
        success: false,
        error: "No image data provided",
      } as AnalysisResponse);
    }

    // Step 1: Detect entities using Python module
    const entityResult = await detectEntities(imageData);

    // Step 2: Update game state with detected entities
    if (entityResult.success && entityResult.entities) {
      gameStateManager.updateState({
        entities: entityResult.entities,
        gamePhase: entityResult.game_phase,
        patterns: entityResult.patterns,
        imageHash: entityResult.image_hash,
      });
    }

    // Step 3: Generate auto tasks based on game state
    const autoTasks = autoTaskGenerator.generateTasks();

    // Step 4: Execute high-priority tasks via multi-agent system
    const executionResults = multiAgentExecutor.processAndExecuteTasks();

    // Step 5: Analyze with Qwen vision (local Ollama first, quantumclaw
    // fallback) for natural language understanding, with heuristic fallback.
    let detection =
      "Live desktop frame captured - interactive workspace detected";
    let suggestion = "Inspect UI elements and execute next planned action";
    let confidence: number | null = null;
    let simulated = true;
    let ollamaOnline = false;

    const applyHeuristicFallback = () => {
      // Heuristic labels only: no model ran, so no confidence is claimed.
      if (entityResult.entities && entityResult.entities.length > 0) {
        const top = entityResult.entities[0];
        detection = `[Heuristic] Detected ${entityResult.entities.length} element(s), top: ${top.name || top.type}`;
        suggestion = `Target ${top.name || "primary element"}`;
      } else {
        detection = "[Heuristic] AI vision unavailable - no analysis performed";
        suggestion = "Start the Ollama qwen3.5:2b backend to enable screen analysis";
      }
    };

    const visionReply = await sendQwenChatRequest(
      [
        buildVisionMessage(
          "Analyze this game/app screenshot. Describe what you see, identify UI elements, and suggest the next action. Be concise.",
          imageData,
        ),
      ],
      { endpoint },
    );
    if (visionReply.success && visionReply.content) {
      detection = extractDetection(visionReply.content);
      suggestion = extractSuggestion(visionReply.content);
      confidence = calculateConfidence(visionReply.content);
      simulated = false;
      ollamaOnline = true;
    } else {
      console.warn(
        "AI endpoint unavailable, using heuristic fallback:",
        visionReply.error,
      );
      applyHeuristicFallback();
    }

    // Get current game state
    const currentState = gameStateManager.getState();
    const agentStats = multiAgentExecutor.getStatistics();

    res.json({
      success: true,
      simulated,
      source: simulated ? "heuristic" : "model",
      detection,
      suggestion,
      confidence,
      entities: entityResult.entities || [],
      autoGeneratedTasks: autoTasks.map((t) => ({
        id: t.id,
        name: t.name,
        description: t.description,
        priority: t.priority,
        confidence: t.confidence,
      })),
      gameState: {
        phase: currentState.gamePhase,
        playerPosition: currentState.playerPosition,
        health: currentState.health,
        entityCount: currentState.entities.size,
        goalCount: currentState.goals.size,
        ollamaOnline,
      },
      // The multi-agent executor only simulates actions; nothing ran on a device.
      executionResults: agentStats.recentResults.map((r) => ({
        success: false,
        simulated: true,
        executed: false,
        executionTime: r.executionTime,
      })),
    } as AnalysisResponse);
  } catch (error) {
    const errorMsg = error instanceof Error ? error.message : "Unknown error";
    console.error("[analyze-screenshot] analysis failed:", errorMsg);
    res.json({
      success: false,
      simulated: true,
      detection: "Analysis unavailable",
      suggestion: "",
      confidence: null,
      entities: [],
      autoGeneratedTasks: [],
      gameState: { phase: "unavailable", entityCount: 0, goalCount: 0 },
      executionResults: [],
      error: "Screenshot analysis failed",
    } as AnalysisResponse);
  }
};

async function detectEntities(imageData: string): Promise<any> {
  return new Promise((resolve) => {
    let resolved = false;
    const safeResolve = (v: any) => {
      if (!resolved) {
        resolved = true;
        resolve(v);
      }
    };
    try {
      const pythonScript = path.join(
        __dirname,
        "../../python-service/entity-detection.py",
      );
      const pythonCmd =
        process.env.PYTHON_CMD ||
        (process.platform === "win32" ? "python" : "python3");

      const python = spawn(pythonCmd, [pythonScript], {
        stdio: ["pipe", "pipe", "pipe"],
      });

      let output = "";
      let errorOutput = "";

      python.stdin.on("error", () => {});
      try {
        python.stdin.write(JSON.stringify({ imageData }));
        python.stdin.end();
      } catch {}

      python.stdout.on("data", (data) => {
        output += data.toString();
      });

      python.stderr.on("data", (data) => {
        errorOutput += data.toString();
      });

      python.on("error", (err) => {
        safeResolve({
          success: false,
          error: `Failed to spawn python (${pythonCmd}): ${err.message}`,
          entities: [],
        });
      });
      python.on("close", (code) => {
        if (code === 0 && output) {
          try {
            const result = JSON.parse(output);
            safeResolve(result);
          } catch (e) {
            safeResolve({
              success: false,
              error: "Failed to parse entity detection response",
              entities: [],
            });
          }
        } else if (!resolved) {
          safeResolve({
            success: false,
            error: errorOutput || `Entity detection failed (code ${code})`,
            entities: [],
          });
        }
      });

      setTimeout(() => {
        try {
          python.kill();
        } catch {}
        safeResolve({
          success: false,
          error: "Entity detection timeout",
          entities: [],
        });
      }, 5000);
    } catch (error) {
      resolve({
        success: false,
        error: error instanceof Error ? error.message : "Unknown error",
        entities: [],
      });
    }
  });
}

function extractDetection(content: string): string {
  const sentences = content.split(/[.!?]\s+/);
  return sentences.slice(0, 2).join(". ").substring(0, 200);
}

function extractSuggestion(content: string): string {
  const suggestionMatch = content.match(
    /(?:suggest|recommend|next|action|should|try)[:\s]+([^.!?]+)/i,
  );
  if (suggestionMatch) {
    return suggestionMatch[1].trim().substring(0, 150);
  }
  const sentences = content.split(/[.!?]\s+/);
  return sentences[sentences.length - 1]?.substring(0, 150) || "";
}

function calculateConfidence(content: string): number {
  let confidence = 0.5;

  if (content.length > 100) confidence += 0.2;
  if (content.length > 300) confidence += 0.15;
  if (/confident|clear|evident|obvious/i.test(content)) confidence += 0.1;
  if (/uncertain|unclear|maybe|might/i.test(content)) confidence -= 0.2;

  return Math.min(Math.max(confidence, 0), 1);
}
